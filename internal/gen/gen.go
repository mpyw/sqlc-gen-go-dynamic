// Package gen emits the Go source for prepared queries.
//
// What it emits is one file of queries: the template constant, the parameter and row types,
// and the method. The surrounding package — the DBTX interface, Queries, and the models — is
// sqlc's own Go codegen's job, and this expects it to be there.
//
// Every query goes through the renderer for now, including one whose template has no
// branches. Such a query renders the same SQL every call and could be emitted as a constant
// with positional arguments, which is what sqlc emits; that specialization is a later step,
// not a change of shape.
package gen

import (
	"fmt"
	"go/format"
	"path"
	"sort"
	"strings"

	"github.com/mpyw/sqlc-gen-go-dynamic/internal/exprtype"
	"github.com/mpyw/sqlc-gen-go-dynamic/internal/query"
)

// Options configures the emitted file.
type Options struct {
	Package string
	Runtime string // import path of the runtime; defaults to the one in this module
}

const defaultRuntime = "github.com/mpyw/sqlc-gen-go-dynamic/dyn"

// File emits one Go file for the given queries.
func File(opts Options, queries []*query.Query) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("gen: no package name")
	}
	if opts.Runtime == "" {
		opts.Runtime = defaultRuntime
	}
	rt := path.Base(opts.Runtime)

	var body strings.Builder
	for _, q := range queries {
		if err := emitQuery(&body, q, rt); err != nil {
			return nil, err
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by sqlc-gen-go-dynamic. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	b.WriteString("import (\n")
	for _, p := range sorted([]string{"context", opts.Runtime}) {
		fmt.Fprintf(&b, "\t%q\n", p)
	}
	b.WriteString(")\n")
	b.WriteString(body.String())

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gen: emitted source does not parse: %w", err)
	}
	return out, nil
}

func emitQuery(b *strings.Builder, q *query.Query, rt string) error {
	sh, err := shapeOf(q.Cmd)
	if err != nil {
		return fmt.Errorf("gen: %s: %w", q.Name, err)
	}
	for _, c := range q.Row {
		if c.Embed != "" {
			// sqlc reports an embedded table as one column with no type, and the columns it
			// stands for live in the catalog. Scanning it needs that list, so it waits until
			// the models do.
			return fmt.Errorf("gen: %s: sqlc.embed(%s) is not supported yet", q.Name, c.Embed)
		}
	}

	lower := unexport(q.Name)
	fmt.Fprintf(b, "\nconst %sSQL = `%s`\n", lower, q.Template)
	fmt.Fprintf(b, "\nvar %sTemplate = %s.MustParse(%sSQL, %q)\n", lower, rt, lower, q.Engine)
	fmt.Fprintf(b, "\n%s\n", exprtype.Declare(q.Params))
	emitScope(b, q.Params)
	if sh.rows {
		emitRow(b, q)
	}
	emitMethod(b, q, sh, lower)
	return nil
}

// shape is what a command does with its rows.
type shape struct {
	rows  bool // the query returns rows
	slice bool // it returns more than one
}

func shapeOf(cmd string) (shape, error) {
	switch cmd {
	case ":many":
		return shape{rows: true, slice: true}, nil
	case ":one":
		return shape{rows: true}, nil
	case ":exec":
		return shape{}, nil
	}
	return shape{}, fmt.Errorf("unsupported command %q", cmd)
}

func emitRow(b *strings.Builder, q *query.Query) {
	fmt.Fprintf(b, "\ntype %sRow struct {\n", q.Name)
	for _, c := range q.Row {
		fmt.Fprintf(b, "\t%s %s\n", exprtype.GoName(c.Name), c.GoType)
	}
	b.WriteString("}\n")
}

// emitScope emits TemplateScope for the params struct, keyed by every spelling the template
// used: a condition may write minAge where the marker beside it writes min_age, and both have
// to resolve. Element structs get none — the renderer reflects them, and folding a Go field
// name reaches every spelling a marker can have named it by.
func emitScope(b *strings.Builder, t *exprtype.Type) {
	fmt.Fprintf(b, "\n// TemplateScope names the fields as the template does.\n")
	fmt.Fprintf(b, "func (p %s) TemplateScope() map[string]any {\n\treturn map[string]any{\n", t.Name)
	for _, m := range t.Fields() {
		for _, s := range m.Spellings {
			fmt.Fprintf(b, "\t\t%q: p.%s,\n", s, exprtype.GoName(m.Name))
		}
	}
	b.WriteString("\t}\n}\n")
}

func emitMethod(b *strings.Builder, q *query.Query, sh shape, lower string) {
	row := q.Name + "Row"
	ret, fail := "error", "err"
	switch {
	case sh.slice:
		ret, fail = "([]"+row+", error)", "nil, err"
	case sh.rows:
		ret, fail = "("+row+", error)", row+"{}, err"
	}

	fmt.Fprintf(b, "\nfunc (q *Queries) %s(ctx context.Context, arg %sParams) %s {\n", q.Name, q.Name, ret)
	fmt.Fprintf(b, "\tstmt, err := %sTemplate.Build(arg)\n", lower)
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn %s\n\t}\n", fail)

	switch {
	case sh.slice:
		b.WriteString("\trows, err := q.db.QueryContext(ctx, stmt.SQL, stmt.Args...)\n")
		fmt.Fprintf(b, "\tif err != nil {\n\t\treturn %s\n\t}\n", fail)
		b.WriteString("\tdefer rows.Close()\n")
		fmt.Fprintf(b, "\tvar items []%s\n", row)
		b.WriteString("\tfor rows.Next() {\n")
		fmt.Fprintf(b, "\t\tvar i %s\n", row)
		fmt.Fprintf(b, "\t\tif err := rows.Scan(%s); err != nil {\n\t\t\treturn nil, err\n\t\t}\n", scanTargets(q))
		b.WriteString("\t\titems = append(items, i)\n\t}\n")
		b.WriteString("\tif err := rows.Err(); err != nil {\n\t\treturn nil, err\n\t}\n")
		b.WriteString("\treturn items, nil\n")

	case sh.rows:
		b.WriteString("\trow := q.db.QueryRowContext(ctx, stmt.SQL, stmt.Args...)\n")
		fmt.Fprintf(b, "\tvar i %s\n", row)
		fmt.Fprintf(b, "\tif err := row.Scan(%s); err != nil {\n\t\treturn %s\n\t}\n", scanTargets(q), fail)
		b.WriteString("\treturn i, nil\n")

	default:
		b.WriteString("\t_, err = q.db.ExecContext(ctx, stmt.SQL, stmt.Args...)\n")
		b.WriteString("\treturn err\n")
	}
	b.WriteString("}\n")
}

func scanTargets(q *query.Query) string {
	out := make([]string, 0, len(q.Row))
	for _, c := range q.Row {
		out = append(out, "&i."+exprtype.GoName(c.Name))
	}
	return strings.Join(out, ", ")
}

func unexport(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func sorted(ss []string) []string {
	out := append([]string(nil), ss...)
	sort.Strings(out)
	return out
}
